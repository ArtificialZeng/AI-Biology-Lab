"""Read-only replay of actual pinned baseline/candidate libraries and analytic oracle.

All numerical/log/cache outputs live in a temporary directory outside the archive.
Only explicit external regeneration writes certificate/manifest proposals.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import importlib.metadata
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent
MANIFEST = 'archive_manifest.json'
CERTIFICATE = 'expected-certificate.json'
SCHEMA = 'gillespy-ode-failure-archive-v1'


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def encode(value):
    return (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def public_paths():
    paths = []
    for path in ROOT.rglob('*'):
        rel = path.relative_to(ROOT)
        require('__pycache__' not in rel.parts and path.suffix not in {'.pyc', '.pyo'},
                'Generated bytecode must be outside the archive: ' + str(rel))
        require(not path.is_symlink(), 'Archive inputs must not be symlinks: ' + str(rel))
        if path.is_file() and rel.as_posix() != MANIFEST:
            paths.append(rel.as_posix())
    return sorted(paths)


def check_archive():
    manifest = json.loads((ROOT / MANIFEST).read_text())
    require(manifest.get('schema') == SCHEMA, 'Unknown archive schema')
    require(manifest.get('algorithm') == 'sha256', 'Unknown hash algorithm')
    require(sorted(manifest['files']) == public_paths(), 'Manifest file coverage mismatch')
    for name, expected in manifest['files'].items():
        require(digest((ROOT / name).read_bytes()) == expected, 'Input hash mismatch: ' + name)
    return manifest


def check_pinned_inputs():
    provenance = json.loads((ROOT / 'source-provenance.json').read_text())
    counts = {}
    for tree, files in provenance['selected_files_sha256'].items():
        actual = {path.relative_to(ROOT / 'vendor' / tree).as_posix()
                  for path in (ROOT / 'vendor' / tree).rglob('*') if path.is_file()}
        require(actual == set(files), 'Vendored file coverage mismatch: ' + tree)
        for name, expected in files.items():
            require(digest((ROOT / 'vendor' / tree / name).read_bytes()) == expected,
                    'Vendored frozen-source mismatch: ' + tree + '/' + name)
        counts[tree] = len(files)
    require(digest((ROOT / 'independent/analytic_oracle.py').read_bytes()) ==
            provenance['independent_spy_sha256'], 'Independent oracle source mismatch')
    for line in (ROOT / 'requirements.txt').read_text().splitlines():
        if line.strip():
            name, version = line.split('==')
            require(importlib.metadata.version(name) == version,
                    'Install pinned dependency ' + line)
    return counts


def decode_object(output, key):
    decoder = json.JSONDecoder()
    for index, char in enumerate(output):
        if char == '{':
            try:
                value, _ = decoder.raw_decode(output[index:])
            except json.JSONDecodeError:
                continue
            if isinstance(value, dict) and key in value:
                return value
    raise RuntimeError('No structured worker output: ' + key)


def checked_analytic(data, candidate):
    cases = {case['label']: case for case in data['results']}
    failures = [('vode_step_exhaustion', -1), ('lsoda_step_exhaustion', -1),
                ('vode_impossible_accuracy', -3), ('reuse_first_failure', -1)]
    for label, backend_code in failures:
        case = cases[label]
        calls = case['backend_calls']
        require(len(calls) == (1 if candidate else 2), label + ': failed-call count')
        first = calls[0]
        require(first['requested'] == 1.0 and 0 <= first['actual'] < first['requested'],
                label + ': actual backend time must precede requested sample')
        require(first['successful'] is False and first['backend_return_code'] == backend_code,
                label + ': expected genuine backend failure')
        if candidate:
            require(case['returned_results'] is False and case['error_type'] == 'SimulationError',
                    label + ': candidate must raise without Results')
            require(case['solver_return_code'] == -1, label + ': wrapper failure status')
            require('requested time' in case['cause'] and 'reached' in case['cause'] and
                    'integrator return code ' + str(backend_code) in case['cause'],
                    label + ': missing actual-time/code diagnostic')
        else:
            require(case['returned_results'] is True and case['solver_return_code'] == 0,
                    label + ': baseline false-success witness')
            require(case['time'] == [0.0, 1.0, 2.0] and case['max_analytic_error'] > 0.5,
                    label + ': baseline must publish incorrect future-labelled rows')
    for label in ['vode_success', 'dopri5_success', 'reuse_successful_retry']:
        case = cases[label]
        require(case['returned_results'] is True and case['solver_return_code'] == 0,
                label + ': successful control/retry failed')
        require(len(case['backend_calls']) == 2, label + ': control call count')
        for call in case['backend_calls']:
            require(call['successful'] is True and
                    math.isclose(call['actual'], call['requested'], rel_tol=0, abs_tol=1e-12),
                    label + ': successful control must reach requested time')
        require(case['max_analytic_error'] < 1e-7 and case['max_conservation_error'] < 1e-12,
                label + ': analytic or conserved-mass control failed')
    return {'genuine_failure_cases': len(failures), 'successful_control_cases': 3,
            'backend_time_and_failure_status_verified': True,
            'failed_rows_rejected' if candidate else 'false_success_reproduced': True,
            'analytic_and_conservation_controls_verified': True,
            'same_instance_retry_verified': True}


def build_certificate():
    counts = check_pinned_inputs()
    with tempfile.TemporaryDirectory(prefix='gillespy-ode-replay-') as directory:
        tmp = Path(directory).resolve()
        require(tmp != ROOT and ROOT not in tmp.parents, 'Temporary files must be outside project')
        environment = dict(os.environ)
        environment['PYTHONDONTWRITEBYTECODE'] = '1'
        environment['MPLCONFIGDIR'] = str(tmp / 'matplotlib')
        environment['XDG_CACHE_HOME'] = str(tmp / 'cache')
        flags = ['-O'] if sys.flags.optimize else []
        jobs = [('analytic', 'baseline'), ('analytic', 'candidate'),
                ('targeted', 'baseline'), ('targeted', 'candidate'), ('whole', 'candidate')]

        def replay(job):
            mode, tree = job
            if mode == 'analytic':
                args = [str(ROOT / 'independent/analytic_oracle.py'), str(ROOT / 'vendor' / tree)]
            else:
                args = [str(ROOT / 'regression_worker.py'), tree, mode]
            command = [sys.executable, *flags, '-B', *args]
            process = subprocess.run(command, cwd=tmp, env=environment,
                                     capture_output=True, text=True, timeout=120)
            (tmp / (mode + '-' + tree + '.stdout')).write_text(process.stdout)
            (tmp / (mode + '-' + tree + '.stderr')).write_text(process.stderr)
            require(process.returncode == 0, mode + '/' + tree + ' worker failed: ' + process.stderr[-1500:])
            return job, decode_object(process.stdout, 'oracle' if mode == 'analytic' else 'worker_result')

        with ThreadPoolExecutor(max_workers=2) as executor:
            outputs = dict(executor.map(replay, jobs))
    baseline = checked_analytic(outputs['analytic', 'baseline'], candidate=False)
    candidate = checked_analytic(outputs['analytic', 'candidate'], candidate=True)
    expected = {('targeted', 'baseline'): {'tests': 7, 'failures': 6, 'errors': 0, 'skipped': 0},
                ('targeted', 'candidate'): {'tests': 7, 'failures': 0, 'errors': 0, 'skipped': 0},
                ('whole', 'candidate'): {'tests': 13, 'failures': 0, 'errors': 0, 'skipped': 0}}
    for key, result in expected.items():
        require(outputs[key]['worker_result'] == result, 'Regression result mismatch: ' + '/'.join(key))
    return {'schema': 'gillespy-ode-replay-certificate-v1', 'ok': True,
            'scope': 'finite real-backend failure and analytic controls; no universal ODE accuracy claim',
            'vendored_frozen_file_counts': counts,
            'baseline': baseline, 'candidate': candidate,
            'baseline_regression_failed_assertions': 6,
            'targeted_regression_methods': 7, 'candidate_whole_ODE_test_methods': 13,
            'temporary_outputs_outside_archive': True,
            'candidate_acceptance_or_human_review_implied': False}


def regenerate(directory):
    require(directory.is_absolute(), 'Output directory must be absolute')
    output = directory.expanduser().resolve()
    require(output != ROOT and ROOT not in output.parents, 'Output must be outside project')
    require(not output.exists(), 'Output must be a new exclusive directory')
    certificate = encode(build_certificate())
    paths = public_paths()
    require(CERTIFICATE in paths, 'Archived certificate is required')
    manifest = {'schema': SCHEMA, 'algorithm': 'sha256',
                'files': {name: digest(certificate if name == CERTIFICATE else (ROOT / name).read_bytes())
                          for name in paths}}
    output.mkdir(parents=False, exist_ok=False)
    (output / CERTIFICATE).write_bytes(certificate)
    (output / MANIFEST).write_bytes(encode(manifest))
    return {'ok': True, 'mode': 'regenerate', 'archive_modified': False,
            'certificate_sha256': digest(certificate), 'exclusive_output': str(output)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='mode', required=True)
    sub.add_parser('verify')
    sub.add_parser('compute')
    regen = sub.add_parser('regenerate')
    regen.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.mode == 'compute':
            print(encode(build_certificate()).decode(), end='')
            return 0
        if args.mode == 'regenerate':
            result = regenerate(args.output_dir)
        else:
            manifest = check_archive()
            computed = encode(build_certificate())
            require(computed == (ROOT / CERTIFICATE).read_bytes(), 'Recomputed certificate differs')
            result = {'ok': True, 'mode': 'verify', 'archive_modified': False,
                      'public_files_checked': len(manifest['files']),
                      'certificate_sha256': digest(computed)}
    except Exception as exc:
        print(json.dumps({'ok': False, 'error': str(exc)}, sort_keys=True))
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
